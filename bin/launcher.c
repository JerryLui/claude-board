/* The program launchd actually runs, so that macOS has something to attribute the
 * daemon's file reads to other than `node` itself.
 *
 * The problem this solves: macOS TCC gates `~/Documents`, `~/Desktop` and `~/Downloads`
 * per application, and a launchd agent gets no grant by inheritance the way a process
 * started from Terminal does. With the plist running `/opt/homebrew/bin/node
 * bin/daemon.mjs` directly, every reference into one of those three directories fails
 * `openSync` with EPERM and lands on the board as "cannot read <path>: EPERM" — which is
 * indistinguishable, from the reviewer's side, from the file not being there.
 *
 * The fix is not to grant node anything. TCC identifies an app by its code signature and
 * its enclosing bundle, so a grant given to `/opt/homebrew/bin/node` is a grant to every
 * node program on the machine, and homebrew's node is ad-hoc signed under a versioned
 * Cellar path, so that grant also dies at the next `brew upgrade node`. Instead this
 * file is compiled at install time into `claude-board.app/Contents/MacOS/claude-board`,
 * ad-hoc signed as a bundle with its own identifier, and named in the plist. macOS then
 * has a distinct application to ask about — one the user can grant the *Documents
 * Folder* checkbox rather than Full Disk Access, and one whose name in System Settings
 * is "claude-board".
 *
 * Why this forks node rather than exec'ing it, which is the entire load-bearing detail:
 * TCC decides against the *responsible process*, and a child inherits its parent's
 * responsible process — that is the mechanism by which everything launched from
 * Terminal.app inherits Terminal's grants. Fork-and-exec therefore leaves the daemon
 * running under this bundle's identity. A plain `execv` would replace this image with
 * node's in the same pid, the code identity would become node's, and the grant would
 * evaporate along with the whole point of the bundle.
 *
 * The two paths are compiled in (launcher_paths.h, generated by install.sh) rather than
 * taken from argv, so that holding the grant is not the same as being able to spend it:
 * an argv-driven launcher would let anything that can rewrite the plist — which is to
 * say any process running as you, including one TCC has refused — run its own code under
 * an identity the user has approved for their Documents folder. Retargeting this one
 * takes a recompile and a resign.
 *
 * The same reasoning extends past argv to the environment, and for the identical reason:
 * the plist is world-readable and user-writable, and its `EnvironmentVariables` dict used
 * to be inherited by the child wholesale. `NODE_OPTIONS` in that dict is arbitrary code
 * that runs the instant node starts — anyone who can write the plist could run anything
 * they want under this bundle's TCC-granted identity, no recompile required. So this
 * launcher builds the child's environment itself rather than passing its own through:
 * HOME, PATH and the three CLAUDE_BOARD_* variables that decide what the daemon may read,
 * serve and write are compiled in exactly like CLAUDE_BOARD_NODE and CLAUDE_BOARD_DAEMON
 * above, and never taken from whatever launchd happened to hand this process. A fourth,
 * CLAUDE_BOARD_REPO_ROOT, is compiled in for a different reason: CLAUDE_BOARD_DAEMON now
 * points inside this bundle (install.sh stages a copy of bin/daemon.mjs and src/ into
 * Contents/Resources ahead of signing), so import.meta.url can no longer tell the daemon
 * where the actual clone is — and it needs to know, because src/handoff.mjs's
 * recoveryCommand() names bin/authorize.mjs by absolute path, and that file is
 * deliberately NOT staged into the bundle (it runs from the clone, registered with Claude
 * Code by path, never through this launcher). It decides no boundary the grant reaches;
 * it is baked in anyway, for the same reason CLAUDE_BOARD_NODE is — an argv- or
 * env-supplied path here would let anything that can rewrite the plist choose what
 * recovery command a locked-out reviewer is told to run. A short allowlist of timing/port
 * knobs — none of which can widen what the grant reaches — is still let through from the
 * parent, by exact name. Everything else, `NODE_OPTIONS` and `CLAUDE_BOARD_SECRET_FILE`
 * included, is simply never copied into the child's environment: not filtered out of it,
 * just never put there. See OVERRIDE_ENV and PASSTHROUGH_NAMES below, and
 * launcher_paths.h for where the compiled-in values come from.
 *
 * One thing this binary does besides supervise node: `claude-board --notify <phase>
 * [cue]` posts the pomodoro boundary notification and exits, without forking anything.
 * That mode exists here, in the file whose whole subject is not spending the grant,
 * because a notification's name, icon and System Settings row come from the bundle of
 * the process that posts it and from nothing else — and macOS refuses to let any
 * executable other than the bundle's own CFBundleExecutable claim that identity, so a
 * helper binary beside this one could not do it (bin/notify.m's header, and QUIRKS.md,
 * record the measurement). The daemon spawns this mode; launchd never does. What argv
 * chooses for the phase is one index into MESSAGES below, never a string that reaches
 * the screen — see NOTIFY_FLAG. The optional third argument names the cue (ADR.md entry
 * 20) — see is_safe_cue_name below for why that one is a character
 * filter rather than a second closed table: the cue vocabulary is whatever
 * /System/Library/Sounds holds on THIS machine, read live by src/cues.mjs (there is no
 * install-time snapshot of it -- QUIRKS.md "soundNamed: searches /System/Library/Sounds
 * and does NOT search the app bundle" is why a staged copy was dropped), which this
 * binary has no compiled-in list of, so "closed set" here means "argv cannot be anything
 * but a bare sound name" rather than "argv must be one of N literal strings".
 */
#include <ctype.h>
#include <errno.h>
#include <signal.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <sys/wait.h>
#include <unistd.h>

/* Generated into the build directory by install.sh: CLAUDE_BOARD_NODE and
 * CLAUDE_BOARD_DAEMON (an absolute path each — CLAUDE_BOARD_DAEMON is the path INSIDE
 * the bundle once a launcher is in use, not the clone's), plus six more used below to
 * build the child's environment — CLAUDE_BOARD_HOME_DIR, CLAUDE_BOARD_PATH,
 * CLAUDE_BOARD_STORE_DIR, CLAUDE_BOARD_REF_ROOTS_VALUE, CLAUDE_BOARD_SERVE_ROOTS_VALUE
 * and CLAUDE_BOARD_REPO_ROOT_VALUE. All eight are C string literals. A header rather than
 * -D so the paths survive the trip through the shell without a second layer of quoting to
 * get wrong. */
#include "launcher_paths.h"

/* --- The child's environment, built once here rather than inherited -------------
 *
 * Two categories. The compiled-in overrides are string-literal concatenations, so there
 * is no runtime cost and no allocation for this half at all — the preprocessor pastes
 * `"NAME="` onto the header's value at compile time, the same way CLAUDE_BOARD_NODE and
 * CLAUDE_BOARD_DAEMON above are already C string literals rather than something built at
 * runtime. Changing any of these six costs a rebuild (and, since that changes the
 * bundle's bytes, a re-sign and a fresh TCC prompt) rather than a plist edit — which is
 * the point for five of them: they decide what the daemon may read, serve and write, so
 * retargeting them should cost as much as retargeting CLAUDE_BOARD_NODE does.
 * CLAUDE_BOARD_REPO_ROOT is the odd one out — it decides no boundary at all, only what
 * path a locked-out reviewer is told to run — but it is baked in on the same footing
 * anyway: an env- or plist-supplied value here would be exactly the kind of thing this
 * file exists to stop a rewritable plist from choosing. */
static const char *const OVERRIDE_ENV[] = {
  "HOME=" CLAUDE_BOARD_HOME_DIR,
  "PATH=" CLAUDE_BOARD_PATH,
  "CLAUDE_BOARD_HOME=" CLAUDE_BOARD_STORE_DIR,
  "CLAUDE_BOARD_REF_ROOTS=" CLAUDE_BOARD_REF_ROOTS_VALUE,
  "CLAUDE_BOARD_SERVE_ROOTS=" CLAUDE_BOARD_SERVE_ROOTS_VALUE,
  "CLAUDE_BOARD_REPO_ROOT=" CLAUDE_BOARD_REPO_ROOT_VALUE,
};
/* An enum, not a `static const int` like FORWARDED_N above: this one sizes the envp
 * array below, and a `const int` is not a compile-time constant to a strict C compiler
 * even when its initializer plainly is — which turns that array into a variable-length
 * array (a silently-accepted GNU extension on this platform, but still a warning worth
 * not having). An enum constant is. */
enum { OVERRIDE_ENV_N = (int)(sizeof(OVERRIDE_ENV) / sizeof(OVERRIDE_ENV[0])) };

/* The passthrough allowlist: copied from the parent's environment only if present, and
 * only under this exact name — no prefix match, no wildcard. Every name here is a
 * timing or port knob; none of them can change what directory gets read, served or
 * written, which is what makes it safe to leave these operator-tunable from the plist
 * without a rebuild. Anything not named here — NODE_OPTIONS chief among them, since it
 * is arbitrary code that runs the instant node starts, and CLAUDE_BOARD_SECRET_FILE,
 * since HOME is baked above precisely so the daemon's default secret path is the only
 * one it can reach — is simply absent from the child's environment: not stripped out of
 * it, just never copied in. */
static const char *const PASSTHROUGH_NAMES[] = {
  "CLAUDE_BOARD_PORT",
  "CLAUDE_BOARD_SHUTDOWN_MS",
  "CLAUDE_BOARD_SSE_HEARTBEAT_MS",
  "CLAUDE_BOARD_TIMEOUT_MS",
  "CLAUDE_BOARD_HANDOFF_TTL_MS",
  "TMPDIR",
};
enum { PASSTHROUGH_N = (int)(sizeof(PASSTHROUGH_NAMES) / sizeof(PASSTHROUGH_NAMES[0])) };

/* Builds one "NAME=value" entry for a passthrough variable actually present in this
 * process's own environment. Three-way return rather than a bare pointer, because
 * "the operator never set this knob" (the common case for most of these) and "malloc
 * failed" both look like NULL otherwise, and only one of those is safe to treat as
 * "just leave it out": an allocation failure here means this process cannot say for
 * certain what it is about to hand a TCC-granted child, which is not a state to exec
 * out of quietly.
 *   returns  1  — present, *out is a malloc'd "NAME=value" the caller must keep past exec
 *            0  — absent from the environment, *out untouched
 *           -1  — present but malloc failed, *out untouched */
static int build_passthrough_entry(const char *name, char **out) {
  const char *value = getenv(name);
  if (value == NULL) return 0;
  size_t len = strlen(name) + 1 /* '=' */ + strlen(value) + 1 /* NUL */;
  char *entry = malloc(len);
  if (entry == NULL) return -1;
  snprintf(entry, len, "%s=%s", name, value);
  *out = entry;
  return 1;
}

/* --- The --notify mode ----------------------------------------------------------
 *
 * Implemented in bin/notify.m, compiled into this same binary (see this file's header
 * for why it cannot be a separate executable). Declared here rather than in a header:
 * there is exactly one caller and exactly one definition, both compiled together by the
 * one `cc` invocation in install.sh, and two arguments are few enough to check by eye
 * against the definition. `body == NULL` requests authorization and posts nothing.
 * `cue_name == NULL` posts with no sound, exactly as a phase set to `None` in
 * src/cues.mjs intends. Returns 0 on success. */
extern int cb_notify(const char *body, const char *cue_name);

static const char *const NOTIFY_FLAG = "--notify";
static const char *const NOTIFY_AUTHORIZE_FLAG = "--notify-authorize";

/* The cue-name argument's own filter, standing in for a closed table the way MESSAGES
 * stands in for the phase argument below. It cannot be a literal enumeration: the cue
 * vocabulary is whatever THIS machine's /System/Library/Sounds holds, read live by
 * src/cues.mjs, and this binary carries no copy of that listing. What it carries instead
 * is the same character-level rule src/cues.mjs's own SAFE_NAME applies before a name is
 * trusted anywhere: one leading alphanumeric, then any run of alphanumerics, spaces,
 * underscores and hyphens, nothing else -- exactly the shape of the 14 stock names macOS
 * ships. An argv byte outside that shape (quotes, slashes, control characters, anything
 * a rewritten plist could try) never reaches cb_notify or UNNotificationSound
 * soundNamed: at all; it is treated the same as no cue being named. Length-bounded too,
 * so this never hands Foundation an unbounded argv string -- 64 comfortably covers every
 * name macOS ships today. */
#define MAX_CUE_NAME_LEN 64
static int is_safe_cue_name(const char *s) {
  size_t len = strlen(s);
  if (len == 0 || len >= MAX_CUE_NAME_LEN) return 0;
  if (!isalnum((unsigned char)s[0])) return 0;
  for (size_t i = 0; i < len; i++) {
    unsigned char c = (unsigned char)s[i];
    if (!(isalnum(c) || c == ' ' || c == '_' || c == '-')) return 0;
  }
  return 1;
}

/* The phases this binary will display something for, paired with the exact sentence it
 * displays. A closed table, matching src/notify.mjs's MESSAGES on the other side of the
 * spawn, and for the identical reason stated there: the string that reaches the screen is
 * a literal out of this array, never a byte of argv. argv chooses WHICH entry, and an
 * unrecognised phase chooses none — it is not a format string, a fallback, or a default.
 * This binary holds the reader's Documents grant, and the plist that spawns it is
 * user-writable; "the notification body is free text from the command line" is exactly
 * the kind of thing that should stay impossible here. */
static const struct { const char *phase; const char *message; } MESSAGES[] = {
  { "work",      "Work interval started" },
  { "break",     "Break started" },
  { "longBreak", "Long break started" },
  /* Not a phase the clock settles on: "test" is what src/notify.mjs's notifyTest sends
   * when the reader ticks Notify, so the question "did that do anything?" is answered by
   * a banner instead of by waiting out an interval. A row in this table, not a special
   * case in main() below, because that is what keeps the property above true of it too.
   * Note for an install that predates it: the daemon selects a row it can no longer find
   * and shows nothing, which is the same failure mode as any unrecognised phase --
   * re-run install.sh to recompile this binary. */
  { "test",      "Notifications are working" },
};
enum { MESSAGES_N = (int)(sizeof(MESSAGES) / sizeof(MESSAGES[0])) };

/* The signals launchd uses to stop a job, plus the two a terminal would send if someone
 * runs this by hand while debugging. SIGKILL is deliberately absent: it cannot be caught,
 * and launchd sending it means the graceful window has already closed. */
static const int FORWARDED[] = { SIGTERM, SIGINT, SIGHUP, SIGQUIT };
static const int FORWARDED_N = (int)(sizeof(FORWARDED) / sizeof(FORWARDED[0]));

static volatile sig_atomic_t child_pid = 0;

/* launchd signals the job; the job is this process, not the node it is holding open. Left
 * unforwarded, `launchctl bootout` would reap the launcher and leave the daemon running
 * with the port still bound — and the next bootstrap would fail on a port in use by a
 * process nothing is supervising any more. */
static void forward(int sig) {
  if (child_pid > 0) {
    /* Nothing to do about a failure here: the child is either already gone (ESRCH, which
     * is the outcome we wanted) or this process is about to die anyway. */
    (void)kill((pid_t)child_pid, sig);
  }
}

int main(int argc, char **argv) {
  /* Before anything else, and before a single line of the supervising path below runs:
   * the notify modes fork nothing, exec nothing, and install no handlers. They are also
   * the only reason this binary reads argv at all — everything the supervising path uses
   * is compiled in, which is the point of the whole file. An unrecognised argument falls
   * through to supervising node, exactly as an argv-less invocation always has, because
   * launchd's invocation is the one that must never depend on getting argv right. */
  if (argc >= 2 && strcmp(argv[1], NOTIFY_AUTHORIZE_FLAG) == 0) {
    return cb_notify(NULL, NULL);
  }
  if (argc >= 3 && strcmp(argv[1], NOTIFY_FLAG) == 0) {
    /* Two arguments' worth of argv, both filtered before either reaches cb_notify:
     * argv[2] selects a row of MESSAGES (and selects nothing at all if it matches no
     * row); argv[3], if present, is a cue name that must pass is_safe_cue_name or it is
     * treated as absent -- src/notify.mjs never sends one that would fail this (cueFor
     * there already collapsed anything isCue() refuses to "no cue"), so this is a second
     * line of defense against a hand-invoked launcher, not the primary one. */
    const char *cue_name = (argc >= 4 && is_safe_cue_name(argv[3])) ? argv[3] : NULL;
    for (int i = 0; i < MESSAGES_N; i++) {
      if (strcmp(argv[2], MESSAGES[i].phase) == 0) {
        return cb_notify(MESSAGES[i].message, cue_name);
      }
    }
    fprintf(stderr, "claude-board: unrecognised notify phase\n");
    return 1;
  }

  struct sigaction sa;
  memset(&sa, 0, sizeof(sa));
  sa.sa_handler = forward;
  sigemptyset(&sa.sa_mask);
  sa.sa_flags = SA_RESTART;

  sigset_t forwarded_set, previous;
  sigemptyset(&forwarded_set);
  for (int i = 0; i < FORWARDED_N; i++) {
    if (sigaction(FORWARDED[i], &sa, NULL) != 0) {
      fprintf(stderr, "claude-board: cannot install handler for signal %d: %s\n",
              FORWARDED[i], strerror(errno));
      return 1;
    }
    sigaddset(&forwarded_set, FORWARDED[i]);
  }

  /* Handlers are installed BEFORE the fork and the forwarded signals blocked ACROSS it,
   * which closes a window that is small and entirely real: a SIGTERM landing after the
   * fork but before `child_pid` is assigned would run the handler against a child_pid of
   * 0, forward nothing, and orphan a daemon that still holds the port. Blocked, the
   * signal waits until the assignment is done and the mask is restored. */
  if (sigprocmask(SIG_BLOCK, &forwarded_set, &previous) != 0) {
    fprintf(stderr, "claude-board: cannot block signals: %s\n", strerror(errno));
    return 1;
  }

  /* Built before fork(), not after: these entries do not depend on which process reads
   * them (the environment is the same in parent and child at this point, since fork()
   * has not happened yet), and failing loudly here — before there is a child to leave
   * half-supervised — is the simpler failure mode. The array lives in main()'s own stack
   * frame, which fork() duplicates whole, so the child's copy is still valid when it
   * execve()s below; nothing here needs to survive past that call, so nothing needs
   * freeing. Sized for the worst case (every passthrough name present) plus one for the
   * NULL terminator execve requires. */
  char *envp[OVERRIDE_ENV_N + PASSTHROUGH_N + 1];
  int envc = 0;
  for (int i = 0; i < OVERRIDE_ENV_N; i++) {
    envp[envc++] = (char *)OVERRIDE_ENV[i];
  }
  for (int i = 0; i < PASSTHROUGH_N; i++) {
    char *entry = NULL;
    int rc = build_passthrough_entry(PASSTHROUGH_NAMES[i], &entry);
    if (rc < 0) {
      fprintf(stderr, "claude-board: cannot build environment for %s: out of memory\n",
              PASSTHROUGH_NAMES[i]);
      return 1;
    }
    if (rc > 0) {
      envp[envc++] = entry;
    }
  }
  envp[envc] = NULL;

  pid_t pid = fork();
  if (pid < 0) {
    fprintf(stderr, "claude-board: fork failed: %s\n", strerror(errno));
    return 1;
  }

  if (pid == 0) {
    /* The child must face launchd's signals with node's own dispositions, not this
     * launcher's: a node that inherited a blocked SIGTERM would ignore the stop it is
     * being asked to perform, and KeepAlive would then be restarting a daemon that never
     * shuts down cleanly. Reset first, unblock second. */
    struct sigaction dfl;
    memset(&dfl, 0, sizeof(dfl));
    dfl.sa_handler = SIG_DFL;
    sigemptyset(&dfl.sa_mask);
    for (int i = 0; i < FORWARDED_N; i++) {
      (void)sigaction(FORWARDED[i], &dfl, NULL);
    }
    (void)sigprocmask(SIG_SETMASK, &previous, NULL);

    /* child_argv, not argv: main() now takes an argv of its own (the notify modes at the
     * top read it), and what the child execs must stay compiled-in — this array shadowing
     * that parameter would put the two one rename apart. */
    char *const child_argv[] = { (char *)CLAUDE_BOARD_NODE, (char *)CLAUDE_BOARD_DAEMON, NULL };
    /* execve, not execv: node inherits exactly the envp built above — the compiled-in
     * overrides and whatever passthrough knobs the parent set — and nothing else this
     * process itself was handed. */
    execve(CLAUDE_BOARD_NODE, child_argv, envp);
    /* Only reachable if the exec failed — a node that was uninstalled or moved since
     * install.sh baked its path in. 127 is the shell's convention for "command not
     * found", and it goes to the daemon's own error log, which is where install.sh
     * already points anyone whose daemon will not come up. */
    fprintf(stderr, "claude-board: cannot exec %s: %s\n", CLAUDE_BOARD_NODE, strerror(errno));
    _exit(127);
  }

  child_pid = pid;
  if (sigprocmask(SIG_SETMASK, &previous, NULL) != 0) {
    fprintf(stderr, "claude-board: cannot restore the signal mask: %s\n", strerror(errno));
    /* Not fatal: the daemon is up and serving. Losing signal forwarding costs a clean
     * bootout, which is worth strictly less than the running daemon it would kill. */
  }

  int status = 0;
  while (waitpid(pid, &status, 0) < 0) {
    /* SA_RESTART does not cover waitpid on every path, and a handler firing mid-wait is
     * the normal case here rather than an exotic one. */
    if (errno != EINTR) {
      fprintf(stderr, "claude-board: waitpid failed: %s\n", strerror(errno));
      return 1;
    }
  }

  /* launchd reads the exit status, and the daemon can exit deliberately: a clean
   * shutdown on SIGTERM is a 0 it chose, not a crash. Reporting the child's status
   * rather than a flat 0 is what keeps that decision the daemon's to make. */
  if (WIFSIGNALED(status)) {
    return 128 + WTERMSIG(status);
  }
  return WEXITSTATUS(status);
}
