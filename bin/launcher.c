static const char *const MENUBAR_PROBE_FLAG = "--probe";

/* The cue-name argument's own filter, standing in for a closed table the way MESSAGES
 * stands in for the phase argument below. It cannot be a literal enumeration: the cue
 * vocabulary is whatever THIS machine's /System/Library/Sounds holds, read live by
 * src/cues.mjs, and this binary carries no copy of that listing. What it carries instead
 * is the same character-level rule src/cues.mjs's own SAFE_NAME applies before a name is
 * trusted anywhere: one leading alphanumeric, then any run of alphanumerics, spaces,
 * underscores and hyphens, nothing else -- exactly the shape of the 14 stock names macOS
 * ships. An argv byte outside that shape (quotes, slashes, control characters, anything
 * a rewritten plist could try) never reaches cb_notify or UNNotificationSound
 * soundNamed: at all; it is treated the same as no cue being named. Length-bounded too,
 * so this never hands Foundation an unbounded argv string -- 64 comfortably covers every
 * name macOS ships today. */
#define MAX_CUE_NAME_LEN 64
static int is_safe_cue_name(const char *s) {
  size_t len = strlen(s);
  if (len == 0 || len >= MAX_CUE_NAME_LEN) return 0;
  if (!isalnum((unsigned char)s[0])) return 0;
  for (size_t i = 0; i < len; i++) {
    unsigned char c = (unsigned char)s[i];
    if (!(isalnum(c) || c == ' ' || c == '_' || c == '-')) return 0;
  }
  return 1;
}

/* The project-folder argument's own filter, for a row whose MESSAGES entry below sets
 * `format` -- ADR.md entry 56. Shaped exactly like is_safe_cue_name above rather than
 * sharing it: the two gate unrelated arguments (a sound name off this machine's
 * /System/Library/Sounds against a folder name off this reader's filesystem) that only
 * happen to want the same character-level rule today, and a future divergence between
 * them should not have to fight a shared function to happen. Longer than
 * MAX_CUE_NAME_LEN because a project folder name runs longer than a sound name in
 * practice; matched by src/notify.mjs's own MAX_FOLDER_NAME_LEN so the two mirrored
 * tables agree on every input, not just on the ones under 64 characters. */
#define MAX_FOLDER_NAME_LEN 80
static int is_safe_folder_name(const char *s) {
  size_t len = strlen(s);
  if (len == 0 || len >= MAX_FOLDER_NAME_LEN) return 0;
  if (!isalnum((unsigned char)s[0])) return 0;
  for (size_t i = 0; i < len; i++) {
    unsigned char c = (unsigned char)s[i];
    if (!(isalnum(c) || c == ' ' || c == '_' || c == '-')) return 0;
  }
  return 1;
}

/* --- The click target -----------------------------------------------------------
 *
 * ADR.md entry 57: a round's banner is clickable, and what a click opens is a plain
 * board URL of THIS daemon -- no credential in it, and none anywhere else on this
 * command line either (a fresh handoff cannot be minted for a click that happens
 * minutes later without a long-lived credential, and one in argv is exactly what this
 * file exists to refuse). The browser's own long-lived session is what authorizes the
 * page; a browser that has never held one lands on the refusal page src/render.mjs
 * already renders, naming src/handoff.mjs's recoveryCommand.
 *
 * That makes this filter the whole of the check on argv[4] before a URL is handed to
 * LaunchServices, which will act on ANY scheme it can resolve -- `file:`, an app's
 * custom scheme, a remote `https:` phishing page. It is deliberately a hand-written
 * scanner rather than NSURL's parse-then-inspect: NSURL accepts a great deal this
 * daemon never emits (userinfo, percent-escapes, backslashes, a second authority),
 * and every one of those is a place where what C decides and what a browser does can
 * differ. What is accepted here is exactly the shape src/server.mjs's boardUrl()
 * builds:
 *
 *     http://<loopback host>[:<port>]/b/<board id>[#<fragment>]
 *
 * with the host set mirroring isLoopbackHost() there (localhost, 127.0.0.1, [::1], or
 * a subdomain of the reserved .localhost TLD), the path exactly one `/b/<id>` segment,
 * and the fragment the board page's own `#open-round` sentinel (src/indexpage.mjs) --
 * which is what makes the click land on the round still waiting rather than on round 1.
 * Anything else is treated as no URL at all: the banner still fires, it just cannot be
 * clicked, the same degradation an unsafe folder name gets.
 *
 * The port is checked too, against `expected_port`, which the daemon passes as its own
 * bound port (argv[5], required -- no port, no click). Loopback alone is not enough:
 * every service on this machine shares it, so a URL naming another one would have a
 * genuine claude-board banner open somebody else's page. The daemon knows the port it
 * bound and already fills this argv, so there is nothing to read out of the environment
 * for it -- which matters, since the environment is the one place a rewritable plist
 * reaches and this file therefore never trusts.
 *
 * NOT static, and the `cb_` prefix says why: bin/menubar.m's popover opens a board URL
 * too -- each of its waiting rows opens the board that round is on, against a URL it read
 * out of `GET /api/waiting` rather than out of argv -- and it calls THIS function to
 * decide whether it may. There is one board-URL pattern in the product and it is here --
 * a second one in Objective-C would be a second opinion about what `/b/../../etc` means,
 * and the two would drift on the first day one of them was tightened. Declared `extern`
 * at the top of bin/menubar.m on the same footing as cb_notify and cb_menubar: one
 * definition, one build, a two-argument signature checkable against the other file by
 * eye. */
#define MAX_BOARD_URL_LEN 200

/* Case-insensitive compare of a bounded span against a lowercase literal. Host names
 * are case-insensitive and src/server.mjs lowercases the Host header before its own
 * check, so a reviewer who typed `LOCALHOST` into the URL bar must not silently lose
 * the click. */
static int span_equals_ci(const char *s, size_t len, const char *lit) {
  if (strlen(lit) != len) return 0;
  for (size_t i = 0; i < len; i++) {
    if (tolower((unsigned char)s[i]) != (unsigned char)lit[i]) return 0;
  }
  return 1;
}

/* Mirrors src/server.mjs's isLoopbackHost for the two forms that can appear unbracketed.
 * `.localhost` is admitted for the reason stated there: RFC 6761 reserves the TLD, so no
 * attacker can own a name under it. */
static int is_loopback_host(const char *host, size_t len) {
  if (span_equals_ci(host, len, "localhost")) return 1;
  if (span_equals_ci(host, len, "127.0.0.1")) return 1;
  static const char SUFFIX[] = ".localhost";
  size_t suffix_len = sizeof(SUFFIX) - 1;
  if (len <= suffix_len) return 0;
  if (!span_equals_ci(host + len - suffix_len, suffix_len, SUFFIX)) return 0;
  if (!isalnum((unsigned char)host[0])) return 0;
  for (size_t i = 0; i < len - suffix_len; i++) {
    unsigned char c = (unsigned char)host[i];
    if (!(isalnum(c) || c == '-' || c == '.')) return 0;
  }
  return 1;
}

/* The daemon's own bound port, from argv. 0 for anything that is not a port, which
 * cb_is_board_url below then refuses every URL against -- a malformed port must cost the
 * click rather than skip the check it exists to make. */
static int parse_port(const char *s) {
  if (s == NULL) return 0;
  size_t len = strlen(s);
  if (len == 0 || len > 5) return 0;
  int value = 0;
  for (size_t i = 0; i < len; i++) {
    if (!isdigit((unsigned char)s[i])) return 0;
    value = value * 10 + (s[i] - '0');
  }
  if (value < 1 || value > 65535) return 0;
  return value;
}

int cb_is_board_url(const char *s, int expected_port) {
  if (expected_port < 1 || expected_port > 65535) return 0;
  size_t len = strlen(s);
  if (len == 0 || len >= MAX_BOARD_URL_LEN) return 0;
  /* Before a single byte is parsed: printable ASCII only. A space, a tab, a control
   * character or a UTF-8 byte in a URL is either an encoding trick or a mistake, and
   * neither is something this daemon ever emits. */
  for (size_t i = 0; i < len; i++) {
    unsigned char c = (unsigned char)s[i];
    if (c <= 0x20 || c >= 0x7f) return 0;
  }

  static const char SCHEME[] = "http://";
  size_t scheme_len = sizeof(SCHEME) - 1;
  /* Not case-insensitive, and http only: this daemon serves plain http on loopback and
   * emits its own URLs lowercase, so there is nothing legitimate to be tolerant of. */
  if (strncmp(s, SCHEME, scheme_len) != 0) return 0;
  const char *p = s + scheme_len;

  if (*p == '[') {
    /* A bracketed literal must be the whole host, exactly as src/server.mjs requires of
     * the Host header -- `[::1]@evil.com` and `[::1].evil.com` are the cases that check
     * was tightened for, and they die here on the same rule: everything after `]` has to
     * be a port or nothing. */
    const char *close = strchr(p, ']');
    if (close == NULL) return 0;
    if (!span_equals_ci(p + 1, (size_t)(close - (p + 1)), "::1")) return 0;
    p = close + 1;
  } else {
    const char *host = p;
    while (*p != '\0' && *p != ':' && *p != '/') p++;
    if (!is_loopback_host(host, (size_t)(p - host))) return 0;
  }

  /* 80 is the port a URL carrying none names, and the Host header carries none on port
   * 80 -- so the comparison below is against a real number in both spellings rather than
   * against "absent", which would have been a hole shaped exactly like the one this
   * check closes. */
  int port = 80;
  if (*p == ':') {
    p++;
    size_t digits = 0;
    port = 0;
    while (isdigit((unsigned char)*p)) {
      port = port * 10 + (*p - '0');
      p++;
      digits++;
    }
    if (digits == 0 || digits > 5) return 0;
  }
  if (port != expected_port) return 0;

  /* Exactly one path segment under /b/, so `/b/../../etc`, `/api/...` and a query
   * string all fail: `.` and `?` are not in the accepted id character set. */
  static const char PREFIX[] = "/b/";
  size_t prefix_len = sizeof(PREFIX) - 1;
  if (strncmp(p, PREFIX, prefix_len) != 0) return 0;
  p += prefix_len;
  size_t id_len = 0;
  while (*p != '\0' && *p != '#') {
    unsigned char c = (unsigned char)*p;
    if (!(isalnum(c) || c == '_' || c == '-')) return 0;
    p++;
    id_len++;
  }
  if (id_len == 0) return 0;
  if (*p == '\0') return 1;

  /* The fragment, if there is one: the board page's own sentinel (`#stranded-round`),
   * which src/ui.mjs resolves to the oldest round still waiting. Not `#open-round`, the
   * index's live-row sentinel, which resolves to the newest open one. A name, never a
   * path -- this check is on the shape, so either spelling crosses and only the daemon
   * decides which is sent. */
  p++;
  size_t fragment_len = 0;
  while (*p != '\0') {
    unsigned char c = (unsigned char)*p;
    if (!(isalnum(c) || c == '-' || c == '_')) return 0;
    p++;
    fragment_len++;
  }
  return fragment_len > 0;
}

/* How long the click-serving process may live, in seconds, from argv[5].
 *
 * The daemon sends the round's own remaining wait, because that is the moment after
 * which a click has nothing left to open (ADR.md entry 50: the deadline passing clears
 * `awaited`). It is a backstop and not the mechanism -- ADR.md entry 57 makes the
 * daemon the owner that kills this process when the reviewer comes back or the round
 * is answered -- but it has to exist, because a wait that simply lapses fires
 * no event a child could be waiting for.
 *
 * Clamped rather than rejected, and defaulted when absent or unparseable: a missing or
 * malformed lifetime must not turn into an immortal process, and must not lose the
 * banner either. The cap is the real guarantee here; the default matches the 40 minutes
 * ADR.md entry 47 fixes every wait at. */
#define CLICK_SECONDS_MAX 3600
#define CLICK_SECONDS_DEFAULT 2400
static int click_seconds_from(const char *s) {
  if (s == NULL) return CLICK_SECONDS_DEFAULT;
  size_t len = strlen(s);
  if (len == 0 || len > 5) return CLICK_SECONDS_DEFAULT;
  int value = 0;
  for (size_t i = 0; i < len; i++) {
    if (!isdigit((unsigned char)s[i])) return CLICK_SECONDS_DEFAULT;
    value = value * 10 + (s[i] - '0');
  }
  if (value < 1) return 1;
  if (value > CLICK_SECONDS_MAX) return CLICK_SECONDS_MAX;
  return value;
}

/* The phases this binary will display something for, paired with the title and the
 * sentence it displays -- a closed table, matching src/notify.mjs's MESSAGES on the
 * other side of the spawn, and for the identical reason stated there: everything that
 * reaches the screen is a literal out of this array, never a byte of argv. argv chooses
 * WHICH entry, and an unrecognised phase chooses none — it is not a format string, a
 * fallback, or a default. This binary holds the reader's Documents grant, and the plist
 * that spawns it is user-writable; "the notification body is free text from the command
 * line" is exactly the kind of thing that should stay impossible here.
 *
 * Two shapes of row, told apart by `format`. NULL there means a fixed `message` and
 * argv[3] (if it passes is_safe_cue_name) names a cue, exactly as every phase below did
 * before this table carried a title of its own. Non-NULL means a folder-format row
 * instead: `message` is unused, `format` is a printf literal with exactly one %s, and
 * argv[3] (if it passes is_safe_folder_name) fills it -- otherwise `unnamed` is shown
 * instead of the row being rejected (ADR.md entry 56). A row is one shape or the other;
 * nothing here needs both a cue and a format argument at once. */
static const struct {
  const char *phase;
  const char *title;
  const char *message;  /* fixed body, for a row with no format argument */
  const char *format;   /* printf literal with one %s, for a row that takes one */
  const char *unnamed;  /* body shown when the format argument is absent or unsafe */
} MESSAGES[] = {
  { "work",      "Pomodoro", "Work interval started",    NULL, NULL },
  { "break",     "Pomodoro", "Break started",             NULL, NULL },
  { "longBreak", "Pomodoro", "Long break started",        NULL, NULL },
  /* Not a phase the clock settles on: "test" is what src/notify.mjs's notifyTest sends
   * when the reader ticks Notify, so the question "did that do anything?" is answered by
   * a banner instead of by waiting out an interval. A row in this table, not a special
   * case in main() below, because that is what keeps the property above true of it too.
   * Note for an install that predates it: the daemon selects a row it can no longer find
   * and shows nothing, which is the same failure mode as any unrecognised phase --
   * re-run install.sh to recompile this binary. */
  { "test",      "Pomodoro", "Notifications are working", NULL, NULL },
  /* The daemon's own banner for a round nobody is watching. No cue of its own -- a
   * choosable sound for the board banner was never in scope, the cue pickers stay the
   * pomodoro clock's -- so this row always plays the system default sound
   * instead (main()'s dispatch below passes use_default_sound=1, cue_name=NULL for it).
   * The folder is what src/indexpage.mjs's `folderName` derives from a board's cwd,
   * crossing here exactly as a cue name always has: as argv[3], filtered before it
   * reaches this table at all. */
  { "round",     "Board",    NULL, "%s: a round is waiting.",   "A round is waiting." },
};
enum { MESSAGES_N = (int)(sizeof(MESSAGES) / sizeof(MESSAGES[0])) };

/* The signals launchd uses to stop a job, plus the two a terminal would send if someone
 * runs this by hand while debugging. SIGKILL is deliberately absent: it cannot be caught,
 * and launchd sending it means the graceful window has already closed. */
static const int FORWARDED[] = { SIGTERM, SIGINT, SIGHUP, SIGQUIT };
static const int FORWARDED_N = (int)(sizeof(FORWARDED) / sizeof(FORWARDED[0]));

static volatile sig_atomic_t child_pid = 0;
/* The --menubar child, or 0 for "there is not one" — which is the state before the fork,
 * after that child has been reaped (it is not restarted, see main()), and permanently on
 * any machine where this process could not learn its own path. Cleared on reap rather than
 * left stale, because pids are recycled and a stale one is a kill aimed at a stranger. */
static volatile sig_atomic_t menubar_pid = 0;

/* launchd signals the job; the job is this process, not the children it is holding open.
 * Left unforwarded, `launchctl bootout` would reap the launcher and leave the daemon
 * running with the port still bound — and the next bootstrap would fail on a port in use
 * by a process nothing is supervising any more. The status item is forwarded the same
 * signal for the tidier half of the same reason: an item left on the menu bar with no
 * supervisor behind it is a control that no longer drives anything. */
static void forward(int sig) {
  /* Nothing to do about a failure here: a child is either already gone (ESRCH, which is
   * the outcome we wanted) or this process is about to die anyway. */
  if (child_pid > 0) {
    (void)kill((pid_t)child_pid, sig);
  }
  if (menubar_pid > 0) {
    (void)kill((pid_t)menubar_pid, sig);
  }
}

/* Run in a child between fork() and execve(), for both children. A child must face
 * launchd's signals with its own dispositions, not this launcher's: a node that inherited
 * a blocked SIGTERM would ignore the stop it is being asked to perform, and KeepAlive
 * would then be restarting a daemon that never shuts down cleanly. The same is true of the
 * status item, which installs handlers of its own the moment it starts (bin/menubar.m) and
 * would never see them fire through an inherited block. Reset first, unblock second —
 * dispositions do not survive execve anyway, but the mask does, and the reset also covers
 * the window before the exec and the case where the exec fails. */
static void reset_signals_for_child(const sigset_t *previous) {
  struct sigaction dfl;
  memset(&dfl, 0, sizeof(dfl));
  dfl.sa_handler = SIG_DFL;
  sigemptyset(&dfl.sa_mask);
  for (int i = 0; i < FORWARDED_N; i++) {
    (void)sigaction(FORWARDED[i], &dfl, NULL);
  }
  (void)sigprocmask(SIG_SETMASK, previous, NULL);
}

/* Stop the status item and reap it, on the way out of main(). Not optional tidiness: this
 * process exiting reparents anything it left running to launchd, so a --menubar child that
 * outlived a `bootout` would be an item on the menu bar with nothing behind it and no job
 * to boot out a second time.
 *
 * Bounded, then SIGKILL, rather than a plain blocking waitpid. The daemon's own restart is
 * on the other side of this call — node exiting is what brings main() here, and launchd's
 * KeepAlive cannot bring it back until this process has actually exited — so a status item
 * wedged in AppKit would otherwise hold the daemon down with it, which is the exact
 * coupling ADR 72 exists to prevent. Two seconds is far longer than a run loop needs to
 * notice a flag and far shorter than launchd's own exit timeout. */
static void stop_menubar_child(void) {
  if (menubar_pid <= 0) return;
  pid_t mb = (pid_t)menubar_pid;
  (void)kill(mb, SIGTERM);
  for (int i = 0; i < 40; i++) {
    if (waitpid(mb, NULL, WNOHANG) == mb) {
      menubar_pid = 0;
      return;
    }
    struct timespec nap = { 0, 50 * 1000 * 1000 };  /* 50ms */
    (void)nanosleep(&nap, NULL);
  }
  (void)kill(mb, SIGKILL);
  (void)waitpid(mb, NULL, 0);
  menubar_pid = 0;
}

int main(int argc, char **argv) {
  /* Before anything else, and before a single line of the supervising path below runs:
   * the notify modes fork nothing, exec nothing, and install no handlers, and --menubar
   * forks and execs nothing either — it installs its own handlers and becomes a run loop.
   * They are also the only reason this binary reads argv at all — everything the
   * supervising path uses is compiled in, which is the point of the whole file. An
   * unrecognised argument falls through to supervising node, exactly as an argv-less
   * invocation always has, because launchd's invocation is the one that must never depend
   * on getting argv right. */
  if (argc >= 2 && strcmp(argv[1], NOTIFY_AUTHORIZE_FLAG) == 0) {
    /* Unaffected by any of the above -- no phase, so no row and no title to pick, and
     * nothing to click either. */
    return cb_notify(NULL, NULL, NULL, 0, NULL, 0);
  }
  if (argc >= 3 && strcmp(argv[1], NOTIFY_FLAG) == 0) {
    /* argv[2] selects a row of MESSAGES, and selects nothing at all if it matches no
     * row -- an install that predates a phase src/notify.mjs has started sending falls
     * straight to "unrecognised notify phase" below, the same silence any unrecognised
     * phase always got. */
    for (int i = 0; i < MESSAGES_N; i++) {
      if (strcmp(argv[2], MESSAGES[i].phase) != 0) continue;

      if (MESSAGES[i].format != NULL) {
        /* A folder-format row: argv[3], filtered through is_safe_folder_name, fills the
         * row's one %s; absent or unsafe falls back to the row's own `unnamed` sentence
         * rather than the phase being rejected (ADR.md entry 56). Always the system
         * default sound -- see the MESSAGES table's own comment on why this row has no
         * cue of its own. */
        char body_buf[MAX_FOLDER_NAME_LEN + 32];
        const char *body;
        if (argc >= 4 && is_safe_folder_name(argv[3])) {
          snprintf(body_buf, sizeof(body_buf), MESSAGES[i].format, argv[3]);
          body = body_buf;
        } else {
          body = MESSAGES[i].unnamed;
        }
        /* argv[4], argv[5] and argv[6] are this row's click target, the port that target
         * must name, and the lifetime that bounds serving it (ADR.md entry 57) -- read
         * here rather than beside the cue above because a fixed-message row has nothing
         * to open: a pomodoro boundary is an event, not a place. A URL that fails
         * cb_is_board_url is treated as absent, so the banner still fires and simply cannot
         * be clicked -- the same degradation the clone install lives with permanently
         * (criterion 19), and the same shape is_safe_folder_name already applies to the
         * name. The port is required and the lifetime is not: without a port there is
         * nothing to check the URL against, while without a lifetime there is a
         * compiled-in default that is still bounded. */
        const char *board_url =
            (argc >= 6 && cb_is_board_url(argv[4], parse_port(argv[5]))) ? argv[4] : NULL;
        int click_seconds = click_seconds_from(argc >= 7 ? argv[6] : NULL);
        return cb_notify(MESSAGES[i].title, body, NULL, 1, board_url, click_seconds);
      }

      /* A fixed-message row: argv[3], if present, is a cue name that must pass
       * is_safe_cue_name or it is treated as absent -- src/notify.mjs never sends one
       * that would fail this (cueFor there already collapsed anything isCue() refuses to
       * "no cue"), so this is a second line of defense against a hand-invoked launcher,
       * not the primary one. */
      const char *cue_name = (argc >= 4 && is_safe_cue_name(argv[3])) ? argv[3] : NULL;
      return cb_notify(MESSAGES[i].title, MESSAGES[i].message, cue_name, 0, NULL, 0);
    }
    fprintf(stderr, "claude-board: unrecognised notify phase\n");
    return 1;
  }
  if (argc >= 2 && strcmp(argv[1], MENUBAR_FLAG) == 0) {
    /* The status item (ADR 72, bin/menubar.m). Reached only as the second child of the
     * fork below, which execs this binary with exactly this one argument -- but it is
     * checked here rather than smuggled through some private channel because the identity
     * that matters is the bundle's, and a mode of the bundle executable is the only shape
     * that keeps it. Nothing is read from argv beyond the flag itself, and the one word
     * that may follow it is the probe seam described above — never anything launchd or
     * the fork below could supply. */
    if (argc >= 3 && strcmp(argv[2], MENUBAR_PROBE_FLAG) == 0) {
      return cb_menubar_probe(argc >= 4 ? argv[3] : NULL, argc >= 5 ? argv[4] : NULL);
    }
    return cb_menubar();
  }

  /* This binary's own path, which the --menubar child below execs. From dyld, not from
   * argv[0]: argv[0] is whatever the caller felt like putting there, and this file's whole
   * subject is that nothing a caller can write gets to choose what runs under an identity
   * the reader granted their Documents folder to.
   *
   * Taken as dyld hands it over, with no realpath(): launchd invokes this by the absolute
   * path in the plist, which is the spelling macOS made its TCC decision about, and this
   * OS has several equally canonical spellings of any path under a home directory (APFS
   * firmlinks — QUIRKS.md). Canonicalising would be trading a path known to work for one
   * nobody has measured. A relative spelling, which only a hand-run launcher can produce,
   * still execs correctly because nothing here ever chdir()s.
   *
   * Failing is not fatal and must not be: an install with no status item is the same
   * install a machine with no compiler gets, and the daemon is the part that matters. */
  char self_path[PATH_MAX];
  uint32_t self_path_size = (uint32_t)sizeof(self_path);
  int have_self_path = (_NSGetExecutablePath(self_path, &self_path_size) == 0);
  if (!have_self_path) {
    fprintf(stderr, "claude-board: cannot determine this executable's own path — "
                    "running without the menu bar item\n");
  }

  /* ADR.md entry 76: past this point is the supervising path -- it is about to fork node
   * and hold this bundle's Documents grant open for as long as that child runs, which is
   * the whole reason a launch that did not come from launchd must not reach it. The
   * click on a stranded banner that fails to activate this bundle (ADR.md entry 75) can
   * have LaunchServices start it exactly this way -- no arguments, the same as launchd's
   * own invocation -- and on an install with a non-default port that becomes a second
   * live daemon racing the real one over one store file until somebody notices and kills
   * it, rather than dying within a second the way a default-port collision would.
   *
   * The check is on CLAUDE_BOARD_LAUNCHD_MARKER (declared above), one exact name checked
   * for one exact value -- the same posture OVERRIDE_ENV and PASSTHROUGH_NAMES already
   * take toward a parent environment this binary does not trust, never "any environment
   * variable at all". It is not argv: nothing here depends on ProgramArguments being
   * wired correctly, which is the point, since launchd's own invocation is the one call
   * that must never depend on getting argv right, and a stray LaunchServices launch has
   * no argv of its own to get wrong either way. What makes this launchd's signal rather
   * than this launcher's own invention: only launchd ever reads
   * ~/Library/LaunchAgents/claude-board.plist and injects its EnvironmentVariables dict
   * into the process it execs (install.sh step 2). A stray LaunchServices launch --
   * a double-click, or the activation macOS attempts after a notification click finds no
   * serving process -- opens the bundle by CFBundleIdentifier, never by consulting that
   * plist, so it can never carry this variable.
   *
   * The cost of getting this check wrong runs one direction only, which is why it is
   * strict rather than lenient: a false negative -- a real launchd start misread as
   * stray -- silently starts no daemon at all. No board would ever open, no round would
   * ever be announced, and every `ask` this bundle would have served fails until someone
   * notices and re-runs install.sh or runs `launchctl kickstart -k` by hand. A false
   * positive costs nothing new beyond what entry 76 already accepts: the class of local
   * attacker who can set this exact variable and hand-launch the bundle can already
   * rewrite the plist to point this binary anywhere, which is the same attacker
   * OVERRIDE_ENV's whole design already declines to defend against.
   *
   * The refusal itself is silent by construction, not by an extra branch bolted on: nothing
   * has forked, no signal handler is installed, and the stderr line below goes to this
   * process's own stderr, which for a bundle LaunchServices opened outside launchd is not
   * attached to anything a reviewer would see on screen -- exactly the posture every
   * other "unrecognised" branch in this file already takes.
   *
   * Known cost, accepted: running this binary by hand with no arguments to supervise a
   * daemon -- which is how entry 72's menu bar child has been getting exercised from a
   * shell -- now does nothing unless CLAUDE_BOARD_LAUNCHD_MARKER=1 is set in that shell
   * first. Supervising has to go through launchd from here on. --notify and --menubar,
   * both dispatched on argv above this point, are untouched. */
  const char *launchd_marker = getenv(LAUNCHD_MARKER_NAME);
  if (launchd_marker == NULL || strcmp(launchd_marker, LAUNCHD_MARKER_VALUE) != 0) {
    fprintf(stderr, "claude-board: no-argument launch missing the launchd marker -- refusing to supervise\n");
    return 0;
  }

  struct sigaction sa;
  memset(&sa, 0, sizeof(sa));
  sa.sa_handler = forward;
  sigemptyset(&sa.sa_mask);
  sa.sa_flags = SA_RESTART;

  sigset_t forwarded_set, previous;
  sigemptyset(&forwarded_set);
  for (int i = 0; i < FORWARDED_N; i++) {
    if (sigaction(FORWARDED[i], &sa, NULL) != 0) {
      fprintf(stderr, "claude-board: cannot install handler for signal %d: %s\n",
              FORWARDED[i], strerror(errno));
      return 1;
    }
    sigaddset(&forwarded_set, FORWARDED[i]);
  }

  /* Handlers are installed BEFORE the forks and the forwarded signals blocked ACROSS both
   * of them, which closes a window that is small and entirely real: a SIGTERM landing
   * after a fork but before that child's pid is assigned would run the handler against a
   * pid of 0, forward nothing, and orphan a daemon that still holds the port — or, for the
   * second child, a status item nothing will ever stop. Blocked, the signal waits until
   * both assignments are done and the mask is restored. */
  if (sigprocmask(SIG_BLOCK, &forwarded_set, &previous) != 0) {
    fprintf(stderr, "claude-board: cannot block signals: %s\n", strerror(errno));
    return 1;
  }

  /* Built before fork(), not after: these entries do not depend on which process reads
   * them (the environment is the same in parent and child at this point, since fork()
   * has not happened yet), and failing loudly here — before there is a child to leave
   * half-supervised — is the simpler failure mode. The array lives in main()'s own stack
   * frame, which fork() duplicates whole, so the child's copy is still valid when it
   * execve()s below; nothing here needs to survive past that call, so nothing needs
   * freeing. Sized for the worst case (every passthrough name present) plus one for the
   * NULL terminator execve requires. */
  char *envp[OVERRIDE_ENV_N + PASSTHROUGH_N + 1];
  int envc = 0;
  for (int i = 0; i < OVERRIDE_ENV_N; i++) {
    envp[envc++] = (char *)OVERRIDE_ENV[i];
  }
  for (int i = 0; i < PASSTHROUGH_N; i++) {
    char *entry = NULL;
    int rc = build_passthrough_entry(PASSTHROUGH_NAMES[i], &entry);
    if (rc < 0) {
      fprintf(stderr, "claude-board: cannot build environment for %s: out of memory\n",
              PASSTHROUGH_NAMES[i]);
      return 1;
    }
    if (rc > 0) {
      envp[envc++] = entry;
    }
  }
  envp[envc] = NULL;

  pid_t pid = fork();
  if (pid < 0) {
    fprintf(stderr, "claude-board: fork failed: %s\n", strerror(errno));
    return 1;
  }

  if (pid == 0) {
    /* See reset_signals_for_child: node must face launchd's signals with its own
     * dispositions, not this launcher's. */
    reset_signals_for_child(&previous);

    /* child_argv, not argv: main() now takes an argv of its own (the notify modes at the
     * top read it), and what the child execs must stay compiled-in — this array shadowing
     * that parameter would put the two one rename apart. */
    char *const child_argv[] = { (char *)CLAUDE_BOARD_NODE, (char *)CLAUDE_BOARD_DAEMON, NULL };
    /* execve, not execv: node inherits exactly the envp built above — the compiled-in
     * overrides and whatever passthrough knobs the parent set — and nothing else this
     * process itself was handed. */
    execve(CLAUDE_BOARD_NODE, child_argv, envp);
    /* Only reachable if the exec failed — a node that was uninstalled or moved since
     * install.sh baked its path in. 127 is the shell's convention for "command not
     * found", and it goes to the daemon's own error log, which is where install.sh
     * already points anyone whose daemon will not come up. */
    fprintf(stderr, "claude-board: cannot exec %s: %s\n", CLAUDE_BOARD_NODE, strerror(errno));
    _exit(127);
  }

  child_pid = pid;

  /* The second child: the status item (ADR 72). Inside the same blocked window as the
   * first, and assigned to menubar_pid before the mask is restored, for the reason stated
   * above the sigprocmask.
   *
   * Everything about it that could fail is survivable and none of it is fatal: no
   * self path, a refused fork, or an exec that cannot find this binary all leave a running
   * daemon and no menu bar item, which is exactly the shape of install a machine with no
   * compiler gets (SPEC criterion 13). The daemon is never made to wait on any of it. */
  if (have_self_path) {
    pid_t menubar = fork();
    if (menubar < 0) {
      fprintf(stderr, "claude-board: cannot fork the menu bar item: %s\n", strerror(errno));
    } else if (menubar == 0) {
      reset_signals_for_child(&previous);
      /* self_path, not argv[0], and the same envp node gets: HOME is what makes the local
       * secret findable and CLAUDE_BOARD_PORT is what names the daemon, and neither should
       * come from a parent environment this file refuses to trust for the daemon. */
      char *const menubar_argv[] = { self_path, (char *)MENUBAR_FLAG, NULL };
      execve(self_path, menubar_argv, envp);
      fprintf(stderr, "claude-board: cannot exec %s %s: %s\n", self_path, MENUBAR_FLAG,
              strerror(errno));
      _exit(127);
    } else {
      menubar_pid = menubar;
    }
  }

  if (sigprocmask(SIG_SETMASK, &previous, NULL) != 0) {
    fprintf(stderr, "claude-board: cannot restore the signal mask: %s\n", strerror(errno));
    /* Not fatal: the daemon is up and serving. Losing signal forwarding costs a clean
     * bootout, which is worth strictly less than the running daemon it would kill. */
  }

  /* waitpid(-1), not waitpid(pid): with two children, waiting on the daemon alone would
   * leave a dead status item unreaped as a zombie for as long as this job runs. What is
   * waited FOR is still the daemon — a --menubar child that dies is reaped and forgotten,
   * never restarted (ADR 72: a crash in menu bar code kills the menu bar alone), and this
   * loop goes back to waiting for node as if nothing happened. */
  int status = 0;
  for (;;) {
    int reaped_status = 0;
    pid_t reaped = waitpid(-1, &reaped_status, 0);
    if (reaped < 0) {
      /* SA_RESTART does not cover waitpid on every path, and a handler firing mid-wait is
       * the normal case here rather than an exotic one. */
      if (errno == EINTR) continue;
      fprintf(stderr, "claude-board: waitpid failed: %s\n", strerror(errno));
      stop_menubar_child();
      return 1;
    }
    if (reaped == pid) {
      status = reaped_status;
      break;
    }
    if (menubar_pid > 0 && reaped == (pid_t)menubar_pid) {
      /* Cleared so nothing later signals a recycled pid, and left at 0 so it is never
       * started again for the life of this job. */
      menubar_pid = 0;
      fprintf(stderr, "claude-board: the menu bar item exited; the daemon is unaffected\n");
    }
  }

  stop_menubar_child();

  /* launchd reads the exit status, and the daemon can exit deliberately: a clean
   * shutdown on SIGTERM is a 0 it chose, not a crash. Reporting the child's status
   * rather than a flat 0 is what keeps that decision the daemon's to make — the DAEMON's,
   * specifically: the status item's exit code never reaches here, or a menu bar crash
   * would be indistinguishable to launchd from the daemon failing. */
  if (WIFSIGNALED(status)) {
    return 128 + WTERMSIG(status);
  }
  return WEXITSTATUS(status);
}
